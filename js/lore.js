const CHAPTER_NAMES = {
  visao:       'VISÃO GERAL',
  reinos:      'REINOS',
  faccoes:     'FACÇÕES',
  personagens: 'PERSONAGENS',
  eventos:     'EVENTOS',
  bestiario:   'BESTIÁRIO',
  reliquias:   'RELÍQUIAS',
};

const ROMAN = ['I','II','III','IV','V','VI','VII','VIII','IX','X','XI','XII','XIII','XIV','XV','XVI'];

const Lore = (() => {
  let currentChapter = 'visao';
  let currentPage    = 0;
  let isFlipping     = false;

  function init() {
    syncTopbar();
    spawnDust();
    openChapter('visao', document.querySelector('.lore-menu-item'));
    updateProgress();
    document.addEventListener('click', e => {
      const sw = document.getElementById('search-wrap');
      if (sw && sw.classList.contains('open') && !sw.contains(e.target)) sw.classList.remove('open');
    });
    document.addEventListener('keydown', e => {
      if (e.key === 'ArrowRight') nextPage();
      if (e.key === 'ArrowLeft')  prevPage();
    });
  }

  function openChapter(id, btn) {
    currentChapter = id;
    currentPage    = 0;
    document.querySelectorAll('.lore-menu-item').forEach(b => b.classList.remove('active'));
    if (btn) btn.classList.add('active');
    renderSpread(false);
    updateNav();
    updateProgress();
  }

  function renderSpread(animate) {
    const pages = CHAPTERS[currentChapter];
    if (!pages || pages.length === 0) return;
    const spread = pages[currentPage];
    const leftEl  = document.getElementById('page-left-inner');
    const rightEl = document.getElementById('page-right-inner');
    if (animate) {
      leftEl.style.opacity  = '0';
      rightEl.style.opacity = '0';
      setTimeout(() => {
        leftEl.innerHTML  = spread.left  || '';
        rightEl.innerHTML = spread.right || '';
        leftEl.style.transition  = 'opacity 0.3s ease';
        rightEl.style.transition = 'opacity 0.3s ease';
        leftEl.style.opacity  = '1';
        rightEl.style.opacity = '1';
      }, 150);
    } else {
      leftEl.innerHTML  = spread.left  || '';
      rightEl.innerHTML = spread.right || '';
      leftEl.style.opacity  = '1';
      rightEl.style.opacity = '1';
    }
    const base = currentPage * 2;
    document.getElementById('page-num-left').textContent  = ROMAN[base]     || (base + 1);
    document.getElementById('page-num-right').textContent = ROMAN[base + 1] || (base + 2);
    document.getElementById('book-chapter-name').textContent = CHAPTER_NAMES[currentChapter] || '';
    const total = CHAPTERS[currentChapter].length;
    document.getElementById('book-page-info').textContent = `Página ${currentPage + 1} de ${total}`;
  }

  function nextPage() {
    const pages = CHAPTERS[currentChapter];
    if (!pages || currentPage >= pages.length - 1 || isFlipping) return;
    flipPage('forward', () => { currentPage++; renderSpread(false); updateNav(); });
  }

  function prevPage() {
    if (currentPage <= 0 || isFlipping) return;
    flipPage('back', () => { currentPage--; renderSpread(false); updateNav(); });
  }

  function flipPage(direction, callback) {
    isFlipping = true;
    const flip  = document.getElementById('page-flip');
    const front = document.getElementById('page-flip-front');
    const back  = document.getElementById('page-flip-back');
    const pages  = CHAPTERS[currentChapter];
    const spread = pages[currentPage];
    if (direction === 'forward') {
      front.innerHTML = spread.right || '';
      const next = pages[currentPage + 1];
      back.innerHTML  = next ? next.left || '' : '';
    } else {
      const prev = pages[currentPage - 1];
      front.innerHTML = prev ? prev.right || '' : '';
      back.innerHTML  = spread.left || '';
    }
    flip.style.pointerEvents = 'none';
    flip.classList.remove('flipping-forward', 'flipping-back');
    void flip.offsetWidth;
    flip.classList.add(direction === 'forward' ? 'flipping-forward' : 'flipping-back');
    setTimeout(() => {
      flip.classList.remove('flipping-forward', 'flipping-back');
      flip.style.pointerEvents = '';
      isFlipping = false;
      callback();
    }, 620);
  }

  function updateNav() {
    const pages = CHAPTERS[currentChapter];
    const total = pages ? pages.length : 1;
    document.getElementById('btn-prev').disabled = currentPage <= 0;
    document.getElementById('btn-next').disabled = currentPage >= total - 1;
    document.getElementById('book-page-info').textContent = `Página ${currentPage + 1} de ${total}`;
  }

  function updateProgress() {
    const total    = Object.keys(CHAPTERS).length;
    const unlocked = Object.keys(CHAPTERS).filter(k => CHAPTERS[k] && CHAPTERS[k].length > 0).length;
    const pct      = Math.round((unlocked / total) * 100);
    document.getElementById('lore-progress-fill').style.width = pct + '%';
    document.getElementById('lore-progress-pct').textContent  = pct + '%';
  }

  function spawnDust() {
    const container = document.getElementById('dust-particles');
    for (let i = 0; i < 18; i++) {
      const d = document.createElement('div');
      d.className = 'dust';
      d.style.left     = Math.random() * 100 + '%';
      d.style.bottom   = Math.random() * 30 + '%';
      d.style.width    = (Math.random() * 3 + 1) + 'px';
      d.style.height   = d.style.width;
      d.style.animationDuration = (Math.random() * 8 + 6) + 's';
      d.style.animationDelay    = (Math.random() * 10) + 's';
      d.style.opacity  = (Math.random() * 0.5 + 0.1).toString();
      container.appendChild(d);
    }
  }

  function syncTopbar() {
    const MAP = {
      kael:   { name: 'Kael',   initial: 'K', level: 8 },
      harley: { name: 'Harley', initial: 'H', level: 7 },
      morgan: { name: 'Morgan', initial: 'M', level: 8 },
      lyria:  { name: 'Lyria',  initial: 'L', level: 7 },
    };
    const id = localStorage.getItem('cos_active_char') || 'kael';
    const c  = MAP[id] || MAP['kael'];
    const n  = document.getElementById('topbar-name');
    const l  = document.getElementById('topbar-level');
    const a  = document.getElementById('topbar-avatar');
    if (n) n.textContent = c.name;
    if (l) l.textContent = c.level;
    if (a) a.textContent = c.initial;
  }

  return { init, openChapter, nextPage, prevPage };
})();

function toggleSearch() {
  const wrap = document.getElementById('search-wrap');
  wrap.classList.toggle('open');
  if (wrap.classList.contains('open')) {
    setTimeout(() => document.getElementById('topbar-search-input').focus(), 310);
  }
}

document.addEventListener('DOMContentLoaded', Lore.init);
